<!-- The AI reports demo: the three items of the app's AI Insights & Reports
     sheet (mobile/src/features/insights/AskAi.tsx), each the REAL prompt the app
     builds over its 60-day sample journal (generated by
     scripts/demo-prompts.test.ts into $lib/demoPrompts + static/demo-prompts).
     The full prompts are fetched on Copy, since they run to 150 KB; the site
     script in app.html swaps the preview and handles Copy. -->
<script lang="ts">
  import { demoReports as reports } from '$lib/demoPrompts';
  const escHtml = (t: string) => t.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const highlight = (t: string) =>
    escHtml(t).replace(/^([A-Z][A-Z0-9 ()/&.'-]*?:)/gm, '<span class="c-key">$1</span>');
  // The sheet's own row icons (ReportRow): download, chart, clipboard.
  const ICONS: Record<string, string> = {
    download: '<path d="M12 4v11M7 10l5 5 5-5M5 20h14" />',
    chart: '<path d="M5 20V10M12 20V4M19 20v-7" />',
    clipboard: '<rect x="6" y="4" width="12" height="17" rx="2.5" /><path d="M9.5 4V3h5v1M9.5 10h5M9.5 14h5" />'
  };
  const titleOf = (r: (typeof reports)[number]) => `${r.key === 'doctor' ? 'medical-summary' : r.key === 'overall' ? 'full-health-report' : 'data-for-prompt'} · ${r.range.replace(/^[^(]*\(|\)$/g, '')}`;
  const footOf = (r: (typeof reports)[number]) => `Built on-device · sample journal · ${r.kb} KB`;
</script>

<div class="v2-dark-tokens">
<section class="section ai" id="ai">
  <div class="ai-glow" aria-hidden="true"></div>
  <div class="wrap">
    <div class="section-head center">
      <h2 class="h2">Try a real prompt on your own AI.</h2>
      <p class="lead">These are the exact prompts the app builds, run over two months of sample data. Copy one, paste it into Claude, Gemini or ChatGPT, and read the report you would get.</p>
    </div>

    <div class="ai-grid">
      <div class="ai-reports">
        <span class="ai-card-tag">AI Insights &amp; Reports</span>
        <div class="ai-chips">
          {#each reports as r, i}
            <button type="button" class="ai-chip{i === 0 ? ' selected' : ''}" data-report={r.key} data-title={titleOf(r)} data-foot={footOf(r)} data-src={r.src} data-preview={r.preview}>
              <span class="ai-chip-ic"><svg viewBox="0 0 24 24" aria-hidden="true">{@html ICONS[r.icon]}</svg></span>
              <span class="ai-chip-t">{r.label}<small>{r.sub}</small></span>
              <i class="ai-check">✓</i>
            </button>
          {/each}
        </div>
        <div class="ai-llms">
          <span class="ai-llm">Claude</span>
          <span class="ai-llm">Gemini</span>
          <span class="ai-llm">ChatGPT</span>
        </div>
      </div>

      <div class="ai-prompt-cell">
      <div class="ai-prompt">
        <div class="aip-bar"><span class="aip-dot"></span><span class="aip-dot"></span><span class="aip-dot"></span><span class="aip-title">{titleOf(reports[0])}</span></div>
        <pre class="aip-body" data-src={reports[0].src}>{@html highlight(reports[0].preview)}</pre>
        <div class="aip-foot"><span class="aip-note">{footOf(reports[0])}</span><button class="aip-copy">Copy &amp; try it</button></div>
      </div>
      </div>
    </div>

    <p class="ai-try">The sample is a made-up person climbing out of a crash, with stand tests, sleep, symptoms, supplements and a magnesium start partway through. The medical summary asks your AI for a print-ready document with tables; the full report walks every area; Data for prompt is just the numbers, for your own question.</p>
  </div>
</section>
</div>

