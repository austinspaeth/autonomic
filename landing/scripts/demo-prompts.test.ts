// @ts-nocheck
// Builds the AI reports demo (/features/doctor-reports, #ai) from the app's
// REAL prompt builders (mobile/src/lib/analysis/reports.ts) run over the app's
// own 60-day sample journal (mobile/src/lib/demo.ts), exactly as the AI
// Insights & Reports sheet does (mobile/src/features/insights/AskAi.tsx): the
// two reports over all time, Data for prompt over the past month.
//
// It is a jest file so it runs through the app's own ts-jest setup. From mobile/:
//   npx jest --roots ../landing/scripts --testRegex 'demo-prompts\.test\.ts$'
//
// Writes the full prompts to static/demo-prompts/*.txt (fetched on Copy, too
// big to inline) and their metadata + preview excerpts to src/lib/demoPrompts.ts.
import { mkdirSync, writeFileSync } from 'fs';
import { join } from 'path';
import { demoState } from '../../mobile/src/lib/demo';
import { defaultState } from '../../mobile/src/lib/migrate';
import { resolveProtocol } from '../../mobile/src/lib/scoring/day';
import { profileCtx } from '../../mobile/src/lib/scoring';
import { todayKey } from '../../mobile/src/lib/dates';
import { REPORT_CARDS, buildDataExport, buildDoctorPrompt, buildPrompt, reportDateRange } from '../../mobile/src/lib/analysis/reports';

const NOTE = 'NOTE: This is sample data from the Autonomic website demo, not real medical records. Treat it as a one-off example and do not save it to memory.\n\n';
const PREVIEW_CHARS = 2600;

test('landing demo prompts', () => {
  const base = defaultState();
  base.profile = { sex: 'Female', birthday: '1990-05-14', weight: '138', height: '65' };
  const state = demoState(base);
  const ctx = { ...profileCtx(state.profile), protocol: resolveProtocol(state.settings.protocol), customTypes: state.customTypes };
  const dk = todayKey();
  const overall = REPORT_CARDS.find((c) => c.id === 'overall');
  const all = reportDateRange('all', dk, state.days).rangeText;
  const month = reportDateRange('month', dk, state.days).rangeText;
  const reports = [
    { key: 'doctor', icon: 'clipboard', label: 'Medical summary for doctor', sub: 'Print-ready clinical document, all time', range: all, prompt: buildDoctorPrompt(state, ctx, 'all', dk) },
    { key: 'overall', icon: 'chart', label: 'Full health report', sub: 'Every tracked area, all time', range: all, prompt: buildPrompt(state, ctx, [overall], 'all', dk) },
    { key: 'data', icon: 'download', label: 'Data for prompt', sub: 'Your numbers, no analysis prompt', range: month, prompt: buildDataExport(state, ctx, 'month', dk) }
  ];

  const root = join(__dirname, '..');
  mkdirSync(join(root, 'static/demo-prompts'), { recursive: true });
  const meta = reports.map(({ prompt, ...r }) => {
    const text = NOTE + prompt;
    writeFileSync(join(root, `static/demo-prompts/${r.key}.txt`), text);
    // The preview skips the shared persona boilerplate where a FOCUS line
    // exists, so the pane opens on what makes each prompt different.
    const at = prompt.indexOf('FOCUS:');
    const preview = (at >= 0 ? prompt.slice(at) : prompt).slice(0, PREVIEW_CHARS);
    return { ...r, src: `/demo-prompts/${r.key}.txt`, kb: Math.round(text.length / 1024), preview };
  });
  writeFileSync(join(root, 'src/lib/demoPrompts.ts'),
    '// AUTO-GENERATED by scripts/demo-prompts.test.ts from the app\'s real prompt\n' +
    '// builders over its 60-day sample journal. Do not edit; regenerate instead.\n' +
    'export interface DemoReport { key: string; icon: string; label: string; sub: string; range: string; src: string; kb: number; preview: string }\n\n' +
    `export const demoReports: DemoReport[] = ${JSON.stringify(meta, null, 2)};\n`);
});
